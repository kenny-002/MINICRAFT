/**
 * Maps block ID to default item ID
 */
export function getItemIdFromBlock(blockId) {
  for (const def of Object.values(ITEM_DEFINITIONS)) {
    if (def.blockId === blockId) {
      return def.id;
    }
  }
  return null;
}

/**
 * Maps item ID to block ID
 */
export function getBlockIdFromItem(itemId) {
  const def = ITEM_DEFINITIONS[itemId];
  return def && def.blockId !== undefined ? def.blockId : null;
}

/**
 * Universal Item Registry helper
 */
export class ItemRegistry {
  static get(itemId) {
    return ITEM_DEFINITIONS[itemId] || null;
  }

  static has(itemId) {
    return !!ITEM_DEFINITIONS[itemId];
  }

  static getAll() {
    return Object.values(ITEM_DEFINITIONS);
  }

  static getByCategory(category) {
    return Object.values(ITEM_DEFINITIONS).filter((item) => item.category === category);
  }

  static isFood(itemId) {
    const item = ITEM_DEFINITIONS[itemId];
    return item && item.category === ITEM_CATEGORY.FOOD;
  }

  static isTool(itemId) {
    const item = ITEM_DEFINITIONS[itemId];
    return item && (item.category === ITEM_CATEGORY.TOOL || item.category === ITEM_CATEGORY.WEAPON);
  }

  static isArmor(itemId) {
    const item = ITEM_DEFINITIONS[itemId];
    return item && item.category === ITEM_CATEGORY.ARMOR;
  }

  static isSeed(itemId) {
    const item = ITEM_DEFINITIONS[itemId];
    return item && item.category === ITEM_CATEGORY.SEED;
  }

  static isBlock(itemId) {
    const item = ITEM_DEFINITIONS[itemId];
    return item && item.category === ITEM_CATEGORY.BLOCK;
  }
}

